#pragma once
#include <cstddef>
#include "Types.h"


/*
		[BaseAllocator]
		OS 힙(malloc/free)을 그대로 쓰는 가장 기본 할당기.
		메모리만 다루고 생성자/소멸자는 호출하지 않는다 (그건 xnew/xdelete가 한다).
*/
class BaseAllocator
{
public:
	static void* Alloc(int32 size);
	static void Release(void* ptr);
};


/*
		[StompAllocator]
		Debug 전용 할당기. 객체마다 OS 페이지를 따로 받고, 데이터를 페이지 끝에 붙여서 돌려준다.
		- 해제하면 페이지를 OS에 바로 반납한다 → 해제 후 접근(Use-After-Free) 시 즉시 Access Violation
		- 객체 바로 뒤는 할당되지 않은 주소다 → 뒤로 넘어가는 오버플로 시 즉시 Access Violation
		- 반환 주소는 malloc과 같은 정렬(ALIGNMENT)을 보장한다. 그래서 size를 ALIGNMENT 배수로 올려 붙이며,
		  올림으로 생긴 빈 바이트(최대 ALIGNMENT - 1) 안의 오버플로는 검출하지 못한다.
		- 객체 하나에 최소 1페이지 + 시스템 콜이 들므로 Release에서는 쓰지 않는다.
*/

/*
		[StompAllocator 동작 상세]

		------------------------------------------------------------------------
		1. 먼저 알아야 할 OS 개념 3가지
		------------------------------------------------------------------------

		① 가상 주소와 페이지
		- 프로그램이 쓰는 주소(0x01A0'0000'0FF0 같은 값)는 가상 주소다. 실제 RAM 위치가 아니다.
		- OS는 가상 주소 공간을 4KB(0x1000) 단위 페이지로 나눈다. 그리고 페이지마다
		  "이 페이지는 실제 RAM의 어디에 있고, 읽기/쓰기가 가능한가"를 페이지 테이블에 적어 둔다.
		- CPU가 메모리에 접근할 때마다 하드웨어(MMU)가 페이지 테이블을 본다.
		  등록되지 않은 페이지에 접근하면 그 명령어에서 바로 예외가 난다.
		  Windows에서는 이게 0xC0000005 Access Violation이다.

		  [참고] StompAllocator는 이 하드웨어 검사를 메모리 오류 탐지기로 활용하는 아이디어다.
		         별도 검사 코드를 넣지 않아도 CPU가 잘못된 접근을 잡아 준다.

		② VirtualAlloc의 RESERVE와 COMMIT
		- MEM_RESERVE    : 가상 주소 범위를 "내가 쓸 거다"라고 예약만 함 (아직 RAM 없음)
		- MEM_COMMIT     : 예약한 범위에 실제 메모리를 연결함 (이제 접근 가능)
		- PAGE_READWRITE : 읽기/쓰기 모두 허용
		- 둘을 같이 주면(MEM_RESERVE | MEM_COMMIT) 한 번에 바로 쓸 수 있는 메모리가 된다.

		③ VirtualAlloc이 돌려주는 주소의 특징
		- 반환 주소는 항상 64KB 경계에 맞춰져 있다 (할당 단위, allocation granularity).
		  그러니 당연히 4KB 경계에도 맞다.
		- 4KB만 요청해도 주소 공간은 64KB를 차지한다. 나머지 60KB는 아무도 쓸 수 없는 빈 주소로 남는다.
		  오버플로를 잡을 수 있는 이유가 이것이다.

		------------------------------------------------------------------------
		2. Alloc — 숫자로 따라가기
		------------------------------------------------------------------------

		예시 A: xnew<MemoryTestKnight>() → size = 8
		  ① 정렬 올림   : 8을 ALIGNMENT(16)의 배수로 올림           → 16
		  ② 페이지 수   : 16B를 담는 데 필요한 4KB 페이지 수 (올림)  → 1
		  ③ 전체 크기   : 페이지 수 × PAGE_SIZE                     → 4096
		  ④ 앞쪽 빈 공간: 전체 크기 − 올린 size = 4096 − 16          → 4080 (0xFF0)
		  ⑤ VirtualAlloc: 4096바이트 요청                           → base = 0x01A0'0000'0000 (예시)
		  ⑥ 반환        : base + 0xFF0                              → 0x01A0'0000'0FF0

		  메모리 모양:
		  0x...0000                                  0x...0FF0           0x...1000
		     |<---------- 빈 공간 4080B (안 씀) --------->|<------ 16B ------>|<-- 미할당 주소 (접근 = 즉시 크래시)
		     |                                            | knight 8B | 여분 8B |
		     ^ base (VirtualAlloc 반환값)                  ^ Alloc 반환값

		  - knight는 0FF0 ~ 0FF7을 쓴다.
		  - 0FF8 ~ 0FFF 8바이트는 정렬 때문에 생긴 여분이다. 할당된 페이지 안이라 여기에 쓰는 것은 잡히지 않는다.
		  - 0x1000부터는 할당되지 않은 주소다. 1바이트만 넘어가도 CPU가 바로 예외를 낸다.

		예시 B: 큰 객체 size = 5000
		  ① 정렬 올림   : 5000 → 5008
		  ② 페이지 수   : 5008 ÷ 4096 올림 → 2
		  ③ 전체 크기   : 8192
		  ④ 앞쪽 빈 공간: 8192 − 5008 = 3184 (0xC70)
		  ⑥ 반환        : base + 0xC70

		  base        base+0xC70              base+0x1000              base+0x2000
		   |<- 빈 공간 ->|<------------- 데이터 5008B ---------------------->|<- 미할당
		   |          페이지 0                  |           페이지 1           |

		  데이터가 페이지 두 개에 걸쳐 있어도, 끝은 정확히 페이지 경계에 붙는다.

		  [핵심 관찰] ④의 앞쪽 빈 공간은 항상 PAGE_SIZE보다 작다 (0 ~ 4080).
		  페이지 수를 "딱 필요한 만큼" 올림으로 정했으니, 남는 공간이 한 페이지를 넘을 수 없기 때문이다.
		  그래서 반환 주소는 언제나 첫 번째 페이지 안에 있다. 이 성질이 Release를 가능하게 한다.

		왜 정렬 올림을 하나
		  올림 없이 size = 4를 그대로 끝에 붙이면 반환 주소가 0x...0FFC가 된다.
		  - 16바이트 정렬을 기대하는 타입(SSE 벡터 __m128 등)은 정렬되지 않은 주소에서 성능이 떨어지거나 크래시가 난다.
		  - xnew는 "malloc과 같은 정렬(16)을 보장한다"는 전제로 STATIC_ASSERT를 걸어 두었다.
		    그러니 할당기를 바꿔도 이 약속을 지켜야 한다.
		  - 대가: 여분 바이트(최대 15B) 안의 오버플로는 잡지 못한다. 정확성(정렬)을 탐지 범위보다 우선한 선택이다.

		------------------------------------------------------------------------
		3. Release — 반환 주소에서 base를 되찾기
		------------------------------------------------------------------------

		Release는 포인터 하나만 받는다. 크기 정보가 없는데 VirtualFree에는 base 주소를 넘겨야 한다.
		앞에서 본 두 가지 성질을 쓰면 된다.
		  1. base는 항상 4KB 경계에 있다 (VirtualAlloc 특성)
		  2. 반환 주소는 항상 첫 번째 페이지 안에 있다 (빈 공간 < 4KB)
		→ 반환 주소를 4KB 경계로 내림하면 base가 된다.

		  예시            반환 주소     % 0x1000    빼면
		  A (size 8)      0x...0FF0    0xFF0       0x...0000 (OK)
		  B (size 5000)   0x...0C70    0xC70       0x...0000 (OK)

		- 주소를 정수로 바꿔 계산해야 하므로 std::uintptr_t를 쓴다 (포인터 크기와 같은 부호 없는 정수).
		- VirtualFree(base, 0, MEM_RELEASE): MEM_RELEASE는 "예약했던 영역 전체를 반납"이라는 뜻이다.
		  범위는 OS가 기억하고 있으므로 size는 반드시 0이어야 한다. 0이 아니면 실패한다.

		  [주의] Alloc이 돌려준 주소가 아닌 값(예: 객체 중간 주소, BaseAllocator로 받은 주소)을 넘기면
		         엉뚱한 base가 계산되어 VirtualFree가 실패한다. 할당기와 해제기는 반드시 짝을 맞춰야 한다.
		         DefaultAllocator 별칭 하나로 xnew/xdelete를 묶는 이유다.

		------------------------------------------------------------------------
		4. 오류를 잡는 순간 — CPU와 OS 안에서 일어나는 일
		------------------------------------------------------------------------

		해제 후 접근 (Use-After-Free)
		  1. Release → VirtualFree(MEM_RELEASE)
		  2. OS가 페이지 테이블에서 그 페이지를 지운다
		  3. 코드가 knight->hp_ = 50; 실행
		  4. CPU(MMU)가 주소 변환 시도 → 페이지 테이블에 없음 → 페이지 폴트
		  5. OS: "이 주소는 이 프로세스에 할당된 적 없음" → EXCEPTION_ACCESS_VIOLATION
		  6. 디버거가 정확히 hp_ = 50 줄에서 멈춤

		free()와 비교
		  - 해제 후 메모리
		      malloc/free    : 힙이 계속 들고 있음 (접근 가능)
		      StompAllocator : OS에 반납 (접근 불가)
		  - 해제 후 쓰기
		      malloc/free    : 조용히 성공 → 힙 관리 정보나 다른 객체가 깨짐 → 한참 뒤 엉뚱한 곳에서 크래시
		      StompAllocator : 그 줄에서 즉시 크래시

		뒤로 넘어가는 오버플로
		  - 객체 끝 = 페이지 끝이다. 다음 주소는 64KB 할당 단위 중 아무도 예약하지 않은 나머지 영역이다.
		  - 넘어가서 쓰는 순간 같은 과정(4~6)으로 크래시가 난다.

		------------------------------------------------------------------------
		5. 한계와 비용
		------------------------------------------------------------------------

		- 메모리      : 8바이트 객체에도 RAM 4KB + 주소 공간 64KB. 객체가 많으면 금방 커짐
		- 속도        : Alloc/Release마다 시스템 콜(커널 진입) → malloc보다 수십 배 이상 느림
		- 주소 재사용 : 해제 후 다시 VirtualAlloc을 하면 OS가 같은 주소를 다시 줄 수 있다.
		                그 뒤의 Use-After-Free는 새 객체를 덮어쓰게 되어 잡히지 않는다.
		                짧은 테스트에서는 드물지만 100%는 아니다
		- 여분 바이트 : 정렬 여분(최대 15B) 안의 오버플로는 잡지 못함

		→ 그래서 Debug에서 버그를 찾는 용도로만 쓰고,
		  Release에서는 실제 할당기(지금은 BaseAllocator, 나중에는 PoolAllocator)를 쓴다.
*/
class StompAllocator
{
public:
	// size는 1 이상. 실패하면 nullptr
	static void* Alloc(int32 size);

	// Alloc이 돌려준 주소만 받는다. nullptr이면 아무 일도 하지 않는다
	static void Release(void* ptr);

private:
	// VirtualAlloc의 할당 단위 (x64 Windows 페이지 크기)
	// 0x1000 = 4KB(4096바이트) - Page 사이즈.
	static constexpr std::size_t PAGE_SIZE = 0x1000;

	// 반환 주소의 정렬. xnew의 STATIC_ASSERT(alignof(Type) <= alignof(max_align_t))와 같은 기준이다
	static constexpr std::size_t ALIGNMENT = alignof(std::max_align_t);
};